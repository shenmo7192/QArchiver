#!/usr/bin/env python3
"""Regenerate the Qt resource manifests (``*.qrc``) for QArchiver.

The manifests only list files, so they are easy to forget when an asset is
added or renamed.  Run this script after touching ``resources/``:

    python3 tools/update_qrc.py

Layout produced by the script::

    resources/icons.qrc          -> /icons/classic, /icons/modern, /icons/file-types
                                     (file-types/{classic,modern}/ nested)
    resources/themes-aero.qrc    -> /themes/aero
    resources/themes-modern.qrc  -> /themes/modern

File paths inside the manifests are relative to the ``resources/`` directory,
which is where the ``.qrc`` files live.
"""

from __future__ import annotations

import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESOURCES = ROOT / "resources"


def walk(directory: Path) -> list[str]:
    """Return every file below *directory* as a resources-relative POSIX path."""
    files: list[str] = []
    for base, dirs, names in os.walk(directory):
        dirs.sort()
        for name in sorted(names):
            files.append(
                (Path(base) / name).relative_to(RESOURCES).as_posix()
            )
    return files


def write_qrc(name: str, title: str, groups: list[tuple[str, list[str]]]) -> None:
    lines = [
        "<!DOCTYPE RCC>",
        '<RCC version="1.0">',
        "<!--",
        f"  {title}",
        "  Generated by tools/update_qrc.py - do not edit by hand.",
        "  由 tools/update_qrc.py 生成，请勿手工修改。",
        "-->",
    ]
    total = 0
    for prefix, files in groups:
        lines.append(f'  <qresource prefix="{prefix}">')
        base = prefix.lstrip("/") + "/"
        for file in files:
            alias = file[len(base):] if file.startswith(base) else file
            lines.append(f'    <file alias="{alias}">{file}</file>')
            total += 1
        lines.append("  </qresource>")
    lines.append("</RCC>")
    (RESOURCES / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{name}: {total} files")


def main() -> int:
    # Every group's resource prefix mirrors the directory below resources/, so a
    # file's resource path is always its path under resources/.
    # 每个资源前缀都与 resources/ 下的目录一致，因此资源路径恒等于文件路径。
    classic = walk(RESOURCES / "icons" / "classic")
    modern = walk(RESOURCES / "icons" / "modern")
    file_types = walk(RESOURCES / "icons" / "file-types")

    write_qrc(
        "icons.qrc",
        "QArchiver icon resources: /icons/classic, /icons/modern, /icons/file-types/{classic,modern}",
        [
            ("/icons/classic", classic),
            ("/icons/modern", modern),
            ("/icons/file-types", file_types),
        ],
    )
    write_qrc(
        "themes-aero.qrc",
        "QArchiver classic (Aero) theme: style sheet and light/dark glyphs.",
        [("/themes/aero", walk(RESOURCES / "themes" / "aero"))],
    )
    write_qrc(
        "themes-modern.qrc",
        "QArchiver modern theme: style sheet and light/dark glyphs.",
        [("/themes/modern", walk(RESOURCES / "themes" / "modern"))],
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
